/**
 * ESLint flat config — Sprint 5.7.30.
 *
 * Migrated from the (deprecated) .eslintrc style to flat config so
 * we can run `eslint .` directly from CI / `pnpm lint`. We keep
 * the same rule set as the previous setup (Next.js core-web-vitals
 * + TypeScript) using `FlatCompat` to bridge the legacy
 * `eslint-config-next` presets into flat-config arrays.
 *
 * Notes:
 *   - We intentionally do NOT use `eslint --max-warnings 0` here.
 *     The repo has accumulated small style nits (prefer-const,
 *     no-unused-vars in dead branches from sprint experiments)
 *     and we want lint to surface them as warnings, not break
 *     the build. Once they are cleaned up we can flip the flag.
 *   - We ignore `.next/`, `out/` (Next.js static export) and
 *     `node_modules/` for obvious reasons.
 *   - The `dist`/`target` dirs are repo-wide Rust build outputs;
 *     they don't exist under `frontend/` but FlatCompat's
 *     `ignores` accepts globs from the root.
 */

import { FlatCompat } from "@eslint/eslintrc";

const compat = new FlatCompat({
  baseDirectory: import.meta.dirname,
});

export default [
  // Global ignores. These are checked BEFORE any rule, so we can
  // be generous with what we exclude — any file matched here is
  // never linted, no matter which ruleset applies below.
  {
    ignores: [
      ".next/**",
      "out/**",
      "node_modules/**",
      "next-env.d.ts",
      // Generated by `next typegen` — do not edit.
      ".next/types/**",
    ],
  },

  // Bridge the legacy presets into flat config. `next/core-web-vitals`
  // covers the React/Next.js-specific lint rules (no-img-element,
  // no-html-link-for-pages, etc.). `next/typescript` adds the
  // TypeScript-aware defaults (no-unused-vars aware of TS types,
  // consistent-type-imports, etc.).
  ...compat.extends("next/core-web-vitals", "next/typescript"),

  // Repo-specific overrides. These run AFTER the extended configs
  // so they take precedence on a per-rule basis.
  {
    rules: {
      // The codebase mixes `"use client"` directive comments with
      // hook usage in the same file (e.g. `app/page.tsx` uses
      // `useState` while the `app/layout.tsx` is a Server
      // Component). We allow that pattern explicitly.
      "react-hooks/rules-of-hooks": "error",
      "react-hooks/exhaustive-deps": "warn",

      // ─── Rollout note (Sprint 5.7.30) ────────────────────────
      // The repo accumulated ~32 unused-imports/vars over the
      // 5.6.x sprints (icons refactored out, props renamed,
      // local state replaced by hooks). Surfacing them as
      // ERRORS would block every PR, which is the opposite of
      // what we want on day-1 of having a lint step in CI.
      //
      // Strategy: report them as WARNINGS now. The CI job runs
      // with `continue-on-error: true` so the badge stays green,
      // but every issue is logged in the run output for whoever
      // wants to grind through them. Once the count drops to 0
      // we flip these back to "error" and remove the
      // continue-on-error flag (one-line change in ci.yml).
      //
      // Allow `_*` prefixed names so we can suppress ad-hoc
      // locals during a refactor without removing the line.
      "@typescript-eslint/no-unused-vars": [
        "warn",
        {
          argsIgnorePattern: "^_",
          varsIgnorePattern: "^_",
          caughtErrorsIgnorePattern: "^_",
        },
      ],

      // Same rollout window: lots of pre-existing `any` slots in
      // Tauri command return types while the API stabilises.
      // Track as warnings until we type the bindings properly.
      "@typescript-eslint/no-explicit-any": "warn",

      // Empty catch blocks appear in `useLocalStorage` and a few
      // event handlers (we log to console.warn). Allow them.
      "no-empty": ["error", { allowEmptyCatch: true }],
    },
  },
];